function normalizeWord(w: string): string {
  return w
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '');
}

/**
 * Translates a Spanish food query to English for USDA API searches.
 * Tries multi-word phrases first, then single words.
 * Unknown words are kept as-is (e.g. "quinoa", "tofu").
 */
export function translateQueryToEnglish(spanishQuery: string): string {
  const normalized = spanishQuery
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '');

  // Build a normalized version of the dictionary
  const normalizedDict: Record<string, string> = {};
  for (const [k, v] of Object.entries(FOOD_TRANSLATIONS)) {
    normalizedDict[normalizeWord(k)] = v;
  }

  // Try to match multi-word phrases (up to 3 words)
  const words = normalized.split(/\s+/).filter(Boolean);
  const result: string[] = [];
  let i = 0;

  while (i < words.length) {
    // Try 3-word phrase
    if (i + 2 < words.length) {
      const phrase3 = words.slice(i, i + 3).join(' ');
      if (normalizedDict[phrase3]) {
        result.push(normalizedDict[phrase3]);
        i += 3;
        continue;
      }
    }
    // Try 2-word phrase
    if (i + 1 < words.length) {
      const phrase2 = words.slice(i, i + 2).join(' ');
      if (normalizedDict[phrase2]) {
        result.push(normalizedDict[phrase2]);
        i += 2;
        continue;
      }
    }
    // Single word
    const word = words[i];
    result.push(normalizedDict[word] ?? word);
    i++;
  }

  return result.join(' ');
}
